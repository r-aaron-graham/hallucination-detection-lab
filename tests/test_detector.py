"""Unit tests for the hallucination detector."""

from __future__ import annotations

import sys
from pathlib import Path

# Ensure the module can be imported when running tests locally
sys.path.append(str(Path(__file__).resolve().parents[1]))

from hallucination_detection_lab import detector  # type: ignore


def test_groundedness_high() -> None:
    context = "A modular data centre uses prefabricated modules to build out capacity."
    answer = "Modular data centres are built from prefabricated modules."
    score = detector.groundedness_score(context, answer)
    assert score > 0.5


def test_groundedness_low() -> None:
    context = "Hydroelectric power is generated by flowing water."
    answer = "Nuclear reactors use uranium to produce electricity."
    score = detector.groundedness_score(context, answer)
    assert score < 0.3


def test_has_citations() -> None:
    answer_with_cit = "The answer is supported by the context [1]"
    answer_without_cit = "This answer lacks any citation markers."
    assert detector.has_citations(answer_with_cit)
    assert not detector.has_citations(answer_without_cit)


def test_evaluate_answer() -> None:
    context = "Solar panels convert sunlight into electricity."
    answer = "Solar panels convert sunlight into electricity [1]."
    hallucinated, score = detector.evaluate_answer(context, answer, threshold=0.3)
    assert not hallucinated
    hallucinated, _ = detector.evaluate_answer(context, "Wind turbines generate power", threshold=0.3)
    assert hallucinated